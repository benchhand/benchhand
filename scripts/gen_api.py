"""Generate the typed API module and the schema reference from the hand-written JSON Schemas.

The JSON Schema 2020-12 files under skills/cad-record/schemas and skills/cad-concept/assets/schemas
are the only source. This script writes two files from one walk of them:

- skills/cad-record/scripts/cad_api.py: TypedDict classes and type aliases, stdlib only, Python 3.11
  compatible so FreeCAD job code can import it.
- docs/schemas.md: the human reference.

`--check` regenerates in memory and fails when a committed output differs. A type cannot express
if/then, dependentRequired, patterns or numeric bounds. The docstrings and the reference list
each of them. The generator drops none.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import keyword
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any
from urllib.parse import urljoin

ROOT = Path(__file__).resolve().parents[1]
# Every directory that holds *.schema.json files. The generator skips a schema outside these
# directories, and the repository test fails when one exists.
SCHEMA_DIRS = ("skills/cad-record/schemas", "skills/cad-concept/assets/schemas")
API_REL = "skills/cad-record/scripts/cad_api.py"
DOC_REL = "docs/schemas.md"
FIX_COMMAND = "python3 scripts/gen_api.py"
SPDX_LINES = ("# SPDX-FileCopyrightText: 2026 Sjors Robroek", "#", "# SPDX-License-Identifier: MPL-2.0")
HEADER = "generated by scripts/gen_api.py \u2014 do not edit. Regenerate with: " + FIX_COMMAND

# Keywords a type cannot express. The docs list each one that a schema uses.
NOTE_KEYS = (
    "pattern", "format", "minimum", "maximum", "exclusiveMinimum", "exclusiveMaximum", "multipleOf",
    "minLength", "maxLength", "minItems", "maxItems", "uniqueItems", "contains", "minContains", "maxContains",
    "minProperties", "maxProperties", "propertyNames", "not", "dependentRequired", "dependentSchemas",
    "unevaluatedProperties", "unevaluatedItems", "patternProperties", "prefixItems",
)
SCALARS = {"string": "str", "integer": "int", "number": "float", "boolean": "bool", "null": "None"}
NO_DEFAULT = object()
# An open object has no static key set: mypy rejects extra keys in a TypedDict literal and ignores
# PEP 728 `extra_items`, so the type is a read-only mapping and keeps the known keys in its docs.
OPEN_OBJECT = "Mapping[str, Any]"
OPEN_NOTE = (
    "Open object: the schema allows other keys, so this is a Mapping[str, Any]. "
    "Type checkers do not check the known keys' names or value types; the table of known keys is documentation."
)
# Notes that record an object closed to extra keys. Any other object accepts them.
CLOSING_NOTES = ("additionalProperties: false", "unevaluatedProperties: false")


def dump(value: Any) -> str:
    return json.dumps(value, separators=(",", ":"), ensure_ascii=False)


def camel(text: str) -> str:
    out = "".join(part[:1].upper() + part[1:] for part in re.split(r"[^0-9A-Za-z]+", text) if part)
    return out if not out[:1].isdigit() else "T" + out


def literal(values: list[Any]) -> str | None:
    """`Literal[...]` for str/int/bool/None values, else None (floats cannot be Literal)."""
    if not all(v is None or isinstance(v, (str, int, bool)) for v in values):
        return None
    return "Literal[" + ", ".join("None" if v is None else dump(v) if isinstance(v, str) else repr(v) for v in values) + "]"


@dataclass
class Schema:
    rel: str
    id: str
    data: dict[str, Any]
    sha256: str  # of the exact file bytes, so any edit needs a regeneration


@dataclass
class Field:
    name: str
    expr: str
    required: bool
    description: str
    default: Any
    notes: list[str]


@dataclass
class TypeDef:
    name: str
    schema: Schema
    pointer: str
    title: str = ""
    description: str = ""
    fields: list[Field] | None = None  # None: an alias
    open: bool = False  # the schema allows keys beyond `fields`

    @property
    def is_class(self) -> bool:
        """A closed object is a TypedDict; an open object and every other type is an alias."""
        return self.fields is not None and not self.open
    alias: str = ""
    notes: list[str] = field(default_factory=list)


def load_schemas(root: Path) -> list[Schema]:
    schemas: list[Schema] = []
    for rel_dir in SCHEMA_DIRS:
        folder = root / rel_dir
        if not folder.is_dir():
            raise ValueError(f"schema directory {rel_dir} does not exist")
        for path in sorted(folder.glob("*.schema.json")):
            raw = path.read_bytes()
            data = json.loads(raw.decode("utf-8"))
            if not isinstance(data, dict) or not isinstance(data.get("$id"), str):
                raise TypeError(f"{path.relative_to(root).as_posix()}: expected an object with a string $id")
            schemas.append(Schema(path.relative_to(root).as_posix(), data["$id"], data, hashlib.sha256(raw).hexdigest()))
    ids = [s.id for s in schemas]
    if len(set(ids)) != len(ids):
        raise ValueError(f"duplicate $id among schemas: {sorted(i for i in set(ids) if ids.count(i) > 1)}")
    return schemas


class Walker:
    def __init__(self, schemas: list[Schema]) -> None:
        self.schemas = schemas
        self.by_id = {s.id: s for s in schemas}
        self.types: dict[tuple[str, str], TypeDef] = {}
        self.names: set[str] = set()

    # -- naming and references -------------------------------------------------------------------

    def unique(self, base: str) -> str:
        name, n = base, 2
        while name in self.names:
            name, n = f"{base}{n}", n + 1
        self.names.add(name)
        return name

    def type_name(self, schema: Schema, pointer: str) -> str:
        tokens = [t.replace("~1", "/").replace("~0", "~") for t in pointer.split("/")[1:]]
        tokens = [t for t in tokens if t not in ("$defs", "properties")]
        stem = Path(schema.rel).name.removesuffix(".schema.json")
        return self.unique(camel("_".join([stem, *tokens])))

    def resolve(self, schema: Schema, ref: str) -> tuple[Schema, str, Any]:
        target_id, _, fragment = urljoin(schema.id, ref).partition("#")
        target = self.by_id.get(target_id)
        if target is None:
            raise ValueError(f"{schema.rel}: $ref {ref!r} points at {target_id!r}, which no schema declares as $id")
        node: Any = target.data
        for token in [t for t in fragment.split("/") if t]:
            token = token.replace("~1", "/").replace("~0", "~")
            try:
                node = node[int(token)] if isinstance(node, list) else node[token]
            except (KeyError, IndexError, ValueError) as err:
                raise ValueError(f"{schema.rel}: $ref {ref!r} does not resolve (no {token!r})") from err
        return target, "/" + "/".join(t for t in fragment.split("/") if t) if fragment.strip("/") else "", node

    def named(self, schema: Schema, pointer: str, node: Any) -> str:
        key = (schema.id, pointer)
        if key in self.types:
            return self.types[key].name
        typedef = TypeDef(self.type_name(schema, pointer), schema, pointer)
        self.types[key] = typedef
        if isinstance(node, dict):
            typedef.title, typedef.description = str(node.get("title", "")), str(node.get("description", ""))
        if self.is_object(schema, pointer, node):
            self.fill_object(typedef, node)
        else:
            typedef.alias = self.inline(schema, pointer, node)
            typedef.notes = self.inline_notes(schema, node)
        return typedef.name

    def register_all(self) -> None:
        for schema in self.schemas:
            if self.structural(schema.data) or "if" in schema.data:
                self.named(schema, "", schema.data)
            for name, node in schema.data.get("$defs", {}).items():
                self.named(schema, f"/$defs/{name}", node)

    # -- type expressions ------------------------------------------------------------------------

    def expr(self, schema: Schema, pointer: str, node: Any) -> str:
        """The type of `node`, hoisting objects into named classes."""
        if isinstance(node, dict) and self.pure_ref(node):
            return self.ref_name(schema, node)
        if self.is_object(schema, pointer, node):
            return self.named(schema, pointer, node)
        return self.inline(schema, pointer, node)

    def ref_name(self, schema: Schema, node: dict[str, Any]) -> str:
        target, target_pointer, target_node = self.resolve(schema, node["$ref"])
        return self.named(target, target_pointer, target_node)

    @staticmethod
    def pure_ref(node: dict[str, Any]) -> bool:
        """A $ref that adds no object keywords of its own (a sibling description or default is fine)."""
        return "$ref" in node and not any(k in node for k in ("properties", "required", "allOf", "oneOf", "anyOf", "if", "unevaluatedProperties", "additionalProperties"))

    def inline(self, schema: Schema, pointer: str, node: Any) -> str:
        if node is True or node == {}:
            return "Any"
        if node is False:
            return "Never"
        for handler in (self.inline_ref, self.inline_value, self.inline_union, self.inline_all_of, self.inline_conditional, self.inline_typed):
            result = handler(schema, pointer, node)
            if result is not None:
                return result
        return "Any"

    def inline_ref(self, schema: Schema, pointer: str, node: dict[str, Any]) -> str | None:
        return self.ref_name(schema, node) if "$ref" in node else None

    def inline_value(self, schema: Schema, pointer: str, node: dict[str, Any]) -> str | None:
        if "const" in node:
            return literal([node["const"]]) or "Any"
        if "enum" in node:
            return literal(node["enum"]) or self.scalar_for(node["enum"])
        return None

    def inline_union(self, schema: Schema, pointer: str, node: dict[str, Any]) -> str | None:
        for key in ("oneOf", "anyOf"):
            members = node.get(key, [])
            if any(self.structural(m) for m in members):
                return self.union([self.expr(schema, f"{pointer}/{key}/{i}", m) for i, m in enumerate(members)])
        return None

    def inline_all_of(self, schema: Schema, pointer: str, node: dict[str, Any]) -> str | None:
        for i, member in enumerate(node.get("allOf", [])):
            if self.structural(member):
                return self.expr(schema, f"{pointer}/allOf/{i}", member)
        return None

    def inline_conditional(self, schema: Schema, pointer: str, node: dict[str, Any]) -> str | None:
        """A schema that only selects between other schemas with if/then/else is the union of its branches."""
        if "if" not in node or "type" in node:
            return None
        branches = self.branches(node, pointer)
        return self.union([self.expr(schema, p, b) for p, b in branches]) if branches else None

    def branches(self, node: dict[str, Any], pointer: str) -> list[tuple[str, Any]]:
        found: list[tuple[str, Any]] = []
        for key in ("then", "else"):
            branch = node.get(key)
            if not isinstance(branch, dict):
                continue
            found += self.branches(branch, f"{pointer}/{key}") if "$ref" not in branch else [(f"{pointer}/{key}", branch)]
        return found

    def inline_typed(self, schema: Schema, pointer: str, node: dict[str, Any]) -> str:
        kind = node.get("type")
        if isinstance(kind, list):
            return self.union([self.inline(schema, pointer, {**node, "type": k}) for k in kind])
        if kind == "array" or (kind is None and ("items" in node or "prefixItems" in node)):
            return self.inline_array(schema, pointer, node)
        if kind == "object":
            extra = node.get("additionalProperties")
            value = self.expr(schema, f"{pointer}/additionalProperties", extra) if isinstance(extra, dict) else "Any"
            return f"dict[str, {value}]"
        return SCALARS.get(kind, "Any") if isinstance(kind, str) else "Any"

    def inline_array(self, schema: Schema, pointer: str, node: dict[str, Any]) -> str:
        if "prefixItems" in node:
            # Records hold JSON arrays, which load as lists, so the type is a list of the positional types.
            return "list[" + self.union([self.expr(schema, f"{pointer}/prefixItems/{i}", m) for i, m in enumerate(node["prefixItems"])]) + "]"
        return "list[" + (self.expr(schema, f"{pointer}/items", node["items"]) if "items" in node else "Any") + "]"

    @staticmethod
    def scalar_for(values: list[Any]) -> str:
        kinds = {"str" if isinstance(v, str) else "bool" if isinstance(v, bool) else "int" if isinstance(v, int) else "float" if isinstance(v, float) else "None" for v in values}
        return " | ".join(sorted(kinds)) if kinds else "Any"

    @staticmethod
    def union(parts: list[str]) -> str:
        literals: list[str] = []
        others: list[str] = []
        for part in parts:
            for piece in re.split(r" \| (?=(?:[^\[\]]|\[[^\]]*\])*$)", part):
                (literals if piece.startswith("Literal[") else others).append(piece)
        if "Any" in others:
            return "Any"
        merged = []
        if literals:
            merged.append("Literal[" + ", ".join(dict.fromkeys(v for lit in literals for v in split_literal(lit))) + "]")
        merged += [p for p in dict.fromkeys(others) if p != "None"]
        if "None" in others:
            merged.append("None")
        return " | ".join(merged)

    @staticmethod
    def structural(node: Any) -> bool:
        return isinstance(node, dict) and any(k in node for k in ("$ref", "type", "enum", "const", "properties", "items", "oneOf", "anyOf", "allOf"))

    # -- objects ---------------------------------------------------------------------------------

    def is_object(self, schema: Schema, pointer: str, node: Any) -> bool:
        if not isinstance(node, dict) or self.pure_ref(node):
            return False
        if any(any(self.structural(m) for m in node.get(key, [])) for key in ("oneOf", "anyOf")):
            return False
        return bool(self.collect(schema, pointer, node, ({}, [], []), set())[0])

    def collect(self, schema: Schema, pointer: str, node: Any, acc: tuple[dict[str, tuple[Schema, str, Any]], list[str], list[str]], seen: set[tuple[str, str]]) -> tuple[dict[str, tuple[Schema, str, Any]], list[str], list[str]]:
        """Merge properties, required names and notes of `node` and its allOf members (following $ref)."""
        props, required, notes = acc
        if not isinstance(node, dict):
            return acc
        if "$ref" in node:
            target, target_pointer, target_node = self.resolve(schema, node["$ref"])
            if (target.id, target_pointer) not in seen:
                self.collect(target, target_pointer, target_node, acc, seen | {(target.id, target_pointer)})
        for name, child in node.get("properties", {}).items():
            if name not in props or self.structural(child):
                props[name] = (schema, f"{pointer}/properties/{name.replace('~', '~0').replace('/', '~1')}", child)
        required.extend(r for r in node.get("required", []) if r not in required)
        notes.extend(self.node_notes(node))
        for i, member in enumerate(node.get("allOf", [])):
            self.collect(schema, f"{pointer}/allOf/{i}", member, acc, seen)
        return acc

    def fill_object(self, typedef: TypeDef, node: dict[str, Any]) -> None:
        props, required, notes = self.collect(typedef.schema, typedef.pointer, node, ({}, [], []), {(typedef.schema.id, typedef.pointer)})
        typedef.fields = []
        for name, (schema, pointer, child) in props.items():
            typedef.fields.append(Field(
                name, self.expr(schema, pointer, child), name in required,
                str(child.get("description", "")) if isinstance(child, dict) else "",
                child.get("default", NO_DEFAULT) if isinstance(child, dict) else NO_DEFAULT,
                self.inline_notes(schema, child),
            ))
        typedef.fields += [Field(name, "Any", True, "", NO_DEFAULT, []) for name in required if name not in props]
        extra = node.get("additionalProperties")
        if isinstance(extra, dict):
            notes.append(f"additionalProperties: {dump(extra)}")
        typedef.notes = list(dict.fromkeys(notes))
        typedef.open = not any(note in CLOSING_NOTES for note in notes)
        if typedef.open:
            typedef.alias = OPEN_OBJECT

    # -- notes: constructs the types cannot carry ------------------------------------------------

    def node_notes(self, node: dict[str, Any]) -> list[str]:
        notes = [f"{key}: {dump(node[key])}" for key in NOTE_KEYS if key in node]
        if node.get("additionalProperties") is False:
            notes.append("additionalProperties: false")
        if node.get("items") is False:
            notes.append("items: false")
        if "if" in node:
            notes.append(f"if {dump(node['if'])} then {dump(node.get('then'))}" + (f" else {dump(node['else'])}" if "else" in node else ""))
        for key in ("oneOf", "anyOf"):
            if key in node and not any(self.structural(m) for m in node[key]):
                notes.append(f"{key}: {dump(node[key])}")
        return notes

    def inline_notes(self, schema: Schema, node: Any, label: str = "") -> list[str]:
        """Notes for a property or alias node, including constraints on inline nested schemas."""
        if not isinstance(node, dict):
            return []
        if self.pure_ref(node):
            return [label + n for n in self.node_notes(node)] + self.child_notes(schema, node, label)
        notes = [label + n for n in self.node_notes(node) if not (label == "" and n == "additionalProperties: false" and self.is_object(schema, "", node))]
        if self.is_object(schema, "", node):
            return []
        if node.get("type") == "object" and "required" in node:
            notes.append(f"{label}required keys: {dump(node['required'])}")
        return notes + self.child_notes(schema, node, label)

    def child_notes(self, schema: Schema, node: dict[str, Any], label: str) -> list[str]:
        """Notes of the schemas nested in `node` (items, extra keys, positions, alternatives and allOf members)."""
        children: list[tuple[str, Any]] = []
        if isinstance(node.get("items"), dict):
            children.append(("items.", node["items"]))
        if isinstance(node.get("additionalProperties"), dict):
            children.append(("additionalProperties.", node["additionalProperties"]))
        children += [(f"prefixItems[{i}].", m) for i, m in enumerate(node.get("prefixItems", []))]
        for key in ("oneOf", "anyOf", "allOf"):
            children += [(f"{key}[{i}].", m) for i, m in enumerate(node.get(key, [])) if isinstance(m, dict)]
        notes: list[str] = []
        for prefix, child in children:
            if not (isinstance(child, dict) and "properties" in child):
                notes.extend(self.inline_notes(schema, child, label + prefix))
        return notes


def split_literal(text: str) -> list[str]:
    inner = text[len("Literal["):-1]
    return re.findall(r'"(?:[^"\\]|\\.)*"|[^,\s][^,]*', inner)


# -- rendering -------------------------------------------------------------------------------------


def docstring(lines: list[str], indent: str) -> list[str]:
    if not lines:
        return []
    body = [line.replace("\\", "\\\\").replace('"""', '\\"\\"\\"') for line in lines]
    return [f'{indent}"""{body[0]}', *[(indent + line).rstrip() for line in body[1:]], f'{indent}"""']


def type_docs(typedef: TypeDef) -> list[str]:
    lines = [typedef.title] if typedef.title else []
    if typedef.description:
        lines += ([""] if lines else []) + typedef.description.splitlines()
    lines += ["", f"Source: {typedef.schema.rel}#{typedef.pointer}"] if lines else [f"Source: {typedef.schema.rel}#{typedef.pointer}"]
    if typedef.notes:
        lines += ["", "Not expressible as types (see the schema):"] + [f"- {n}" for n in typedef.notes]
    if typedef.open:
        lines += ["", OPEN_NOTE, "Known keys: " + ", ".join(f"{f.name}: {f.expr}{'' if f.required else ' (optional)'}" for f in typedef.fields or [])]
    described = [f for f in typedef.fields or [] if f.description or f.default is not NO_DEFAULT or f.notes]
    if described:
        lines += ["", "Field notes:"]
        for f in described:
            lines.append(f"- {f.name}: " + "; ".join(([f.description] if f.description else []) + ([f"default {dump(f.default)}"] if f.default is not NO_DEFAULT else []) + f.notes))
    return lines


def wrap(f: Field, quote: bool) -> str:
    """The field annotation. A quoted expression is a forward reference to a later type."""
    return f"{'Required' if f.required else 'NotRequired'}[{json.dumps(f.expr) if quote else f.expr}]"


def render_class(typedef: TypeDef, quoted: set[tuple[str, str]]) -> list[str]:
    assert typedef.fields is not None
    docs = type_docs(typedef)
    if all(f.name.isidentifier() and not keyword.iskeyword(f.name) for f in typedef.fields):
        out = [f"class {typedef.name}(TypedDict):", *docstring(docs, "    ")]
        out += [f"    {f.name}: {wrap(f, (typedef.name, f.name) in quoted)}" for f in typedef.fields]
        return out
    out = ["# " + line if line else "#" for line in docs]
    out.append(f"{typedef.name} = TypedDict(")
    out.append(f'    "{typedef.name}",')
    out.append("    {")
    out += [f"        {json.dumps(f.name)}: {wrap(f, (typedef.name, f.name) in quoted)}," for f in typedef.fields]
    out += ["    },", ")"]
    return out


def render_alias(typedef: TypeDef) -> list[str]:
    out = ["# " + line if line else "#" for line in type_docs(typedef)]
    return [*out, f"{typedef.name} = {typedef.alias}"]


NAME = re.compile(r"[A-Za-z_]\w*")


class TypeOrder:
    """Depth-first definition order, so every annotation evaluates at import. `quoted` collects the
    fields that close a cycle. TypedDict ignores Required and NotRequired inside a string
    annotation, so the module cannot defer all annotations."""

    def __init__(self, types: list[TypeDef]) -> None:
        self.by_name = {t.name: t for t in types}
        self.done: list[TypeDef] = []
        self.emitted: set[str] = set()
        self.state: set[str] = set()
        self.waits: dict[str, str] = {}
        self.pending: dict[str, list[TypeDef]] = {}
        self.quoted: set[tuple[str, str]] = set()
        for typedef in sorted(types, key=lambda t: t.name):
            self.visit(typedef)

    def emit(self, typedef: TypeDef) -> None:
        self.done.append(typedef)
        self.emitted.add(typedef.name)
        for waiting in self.pending.pop(typedef.name, []):
            self.emit(waiting)

    def dependencies(self, expr: str) -> list[str]:
        return [word for word in NAME.findall(expr) if word in self.by_name]

    def visit(self, typedef: TypeDef) -> None:
        if typedef.name in self.state:
            return
        self.state.add(typedef.name)
        wait = self.visit_alias(typedef) if not typedef.is_class else self.visit_class(typedef)
        if wait:
            self.waits[typedef.name] = wait
            self.pending.setdefault(wait, []).append(typedef)
        else:
            self.emit(typedef)

    def visit_class(self, typedef: TypeDef) -> str:
        for f in typedef.fields or []:
            for word in self.dependencies(f.expr):
                self.visit(self.by_name[word])
                if word not in self.emitted:
                    self.quoted.add((typedef.name, f.name))
        return ""

    def visit_alias(self, typedef: TypeDef) -> str:
        """Return the class this alias must follow, or an empty string to emit the alias now."""
        wait = ""
        for word in self.dependencies(typedef.alias):
            if word == typedef.name:
                raise ValueError(f"type alias {typedef.name} refers to itself")
            self.visit(self.by_name[word])
            if word in self.emitted:
                continue
            # The alias needs a class that is still open: emit the alias right after that class.
            wait = word if self.by_name[word].is_class else self.waits.get(word, "")
            if not wait:
                raise ValueError(f"type alias {typedef.name} is part of an alias cycle with {word}")
        return wait


def order_types(types: list[TypeDef]) -> tuple[list[TypeDef], set[tuple[str, str]]]:
    order = TypeOrder(types)
    return order.done, order.quoted


HASH_LINE = re.compile(r"schema-sha256 ([0-9a-f]{64}) (\S+)")


def hash_lines(schemas: list[Schema]) -> list[str]:
    return [f"schema-sha256 {s.sha256} {s.rel}" for s in sorted(schemas, key=lambda s: s.rel)]


def schema_drift(expected: str, committed: str) -> list[str]:
    """Name each schema whose recorded hash differs from the current file, and each schema the outputs lack or still list."""
    now = {rel: digest for digest, rel in HASH_LINE.findall(expected)}
    then = {rel: digest for digest, rel in HASH_LINE.findall(committed)}
    return [
        *[f"schema changed {rel}" for rel in sorted(now) if rel in then and now[rel] != then[rel]],
        *[f"schema added {rel}" for rel in sorted(now.keys() - then.keys())],
        *[f"schema removed {rel}" for rel in sorted(then.keys() - now.keys())],
    ]


def render_api(types: list[TypeDef], schemas: list[Schema]) -> str:
    ordered, quoted = order_types(types)
    body: list[str] = []
    for typedef in ordered:
        body += (render_class(typedef, quoted) if typedef.is_class else render_alias(typedef)) + ["", ""]
    text = "\n".join(body)
    imports = ["Any"] * bool(re.search(r"\bAny\b", text)) + ["Never"] * bool(re.search(r"\bNever\b", text)) + ["Literal"] * ("Literal[" in text)
    imports += ["NotRequired"] * ("NotRequired[" in text) + ["Required"] * bool(re.search(r"(?<!Not)Required\[", text)) + ["TypedDict"] * any(t.is_class for t in types)
    names = sorted(t.name for t in types)
    head = [
        *SPDX_LINES,
        f"# {HEADER}",
        *[f"# {line}" for line in hash_lines(schemas)],
        '"""Typed shapes of the CAD record and concept JSON Schemas.',
        "",
        "Standard library only and Python 3.11 compatible, so FreeCAD job code can import it. Each schema",
        "object that forbids extra keys is a TypedDict; an object that allows them is a Mapping[str, Any], so",
        "its known keys are documented but not checked; each shared definition is a type alias. Types cannot express if/then,",
        "dependentRequired, patterns, numeric bounds, uniqueness, additionalProperties: false or oneOf",
        "exclusivity; the docstrings and comments list them. The JSON Schemas stay authoritative:",
        "validate with them (schema_registry.py) and use these types for editor and type-checker help.",
        '"""',
        "",
        *["from collections.abc import Mapping"] * any(t.open for t in types),
        f"from typing import {', '.join(sorted(imports))}",
        "",
        "__all__ = [",
        *[f'    "{n}",' for n in names],
        "]",
        "",
        "",
    ]
    return "\n".join(head) + text.rstrip("\n") + "\n"


def md_cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def field_table(typedef: TypeDef) -> list[str]:
    if not typedef.fields:
        return []
    out = ["| Field | Type | Required | Default | Description |", "| --- | --- | --- | --- | --- |"]
    for f in typedef.fields:
        default = "" if f.default is NO_DEFAULT else f"`{md_cell(dump(f.default))}`"
        out.append(f"| `{f.name}` | `{md_cell(f.expr)}` | {'yes' if f.required else 'no'} | {default} | {md_cell(f.description)} |")
    return [*out, ""]


def doc_section(typedef: TypeDef) -> list[str]:
    out = [f"### {typedef.name}", "", f"Source: `{typedef.pointer}`" if typedef.pointer else "Source: schema root", ""]
    out += [f"**{typedef.title}**", ""] if typedef.title else []
    out += [typedef.description, ""] if typedef.description else []
    out += [] if typedef.is_class else [f"Alias of `{typedef.alias}`", ""]
    out += [OPEN_NOTE, "", "Known keys:", ""] if typedef.open else []
    out += field_table(typedef)
    notes = [*typedef.notes, *[f"`{f.name}`: {n}" for f in typedef.fields or [] for n in f.notes]]
    return out + (["Constraints not expressed by the type:", ""] + [f"- {md_cell(n)}" for n in notes] + [""] if notes else [])


def render_doc(schemas: list[Schema], types: list[TypeDef]) -> str:
    out = [f"<!-- {HEADER}", *hash_lines(schemas), "-->", "", "# Schema reference", "",
           "Every type below is generated from the JSON Schemas listed in its section. The schemas stay authoritative;",
           "types show shape only, so the constraints a type cannot express are listed under each type.", ""]
    for schema in schemas:
        out += [f"## {Path(schema.rel).name}", "", f"- File: `{schema.rel}`", f"- `$id`: `{schema.id}`", ""]
        out += [str(schema.data["title"]), ""] if schema.data.get("title") else []
        for typedef in sorted((t for t in types if t.schema is schema), key=lambda t: t.name):
            out += doc_section(typedef)
    return "\n".join(out).rstrip("\n") + "\n"


def generate(root: Path) -> dict[str, str]:
    """Relative output path -> file text, from the schemas under `root`."""
    schemas = load_schemas(root)
    walker = Walker(schemas)
    walker.register_all()
    types = list(walker.types.values())
    return {API_REL: render_api(types, schemas), DOC_REL: render_doc(schemas, types)}


def output_drift(root: Path, outputs: dict[str, str]) -> list[str]:
    """Missing or stale outputs, plus each schema whose bytes differ from the hash the outputs record."""
    drift: list[str] = []
    for rel, text in outputs.items():
        path = root / rel
        if not path.is_file():
            drift.append(f"missing {rel}")
            continue
        committed = path.read_text(encoding="utf-8")
        if committed != text:
            drift.append(f"stale {rel}")
            drift += [d for d in schema_drift(text, committed) if d not in drift]
    return drift


def main(argv: list[str] | None = None, root: Path = ROOT) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when a committed output differs from the schemas")
    args = parser.parse_args(argv)
    try:
        outputs = generate(root)
    except (OSError, ValueError, TypeError, KeyError) as error:
        print(f"FAIL: {error}", file=sys.stderr)
        return 1
    if not args.check:
        for rel, text in outputs.items():
            path = root / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"generated {rel}")
        return 0
    drift = output_drift(root, outputs)
    if drift:
        print("FAIL: generated files differ from the JSON Schemas:", file=sys.stderr)
        for item in drift:
            print(f"  {item}", file=sys.stderr)
        print(f"Run {FIX_COMMAND}", file=sys.stderr)
        return 1
    print(f"PASS: {len(outputs)} generated files current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

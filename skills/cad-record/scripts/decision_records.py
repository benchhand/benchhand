"""Decision records in the MADR 4.0.0 layout: `DR-###-slug.md`, with a generated `index.md` beside them.

A record is a Markdown file with YAML front matter (`status` and `date`, and optional `decision-makers`,
`consulted` and `informed`) and the MADR sections: the `# title`, `## Context and Problem Statement`,
`## Decision Drivers`, `## Considered Options`, `## Decision Outcome` (`Chosen option: "X", because Y.`
with `### Consequences` and `### Confirmation`), `## Pros and Cons of the Options` and `## More Information`.
MADR 4.0.0: https://adr.github.io/madr/

`write_decision` writes the next record of a directory and regenerates the index. `read_decision` and
`read_decisions` parse records into `DecisionRecord`. Both refuse anything off the template with
`DecisionRecordError`, naming the file and the rule. A `DR-*.md` file whose
name is not `DR-###-slug.md` raises too, so an older record shows up instead of vanishing from the index.

Load it by path and register it in `sys.modules` as `cad_record_decision_records`.
"""

from __future__ import annotations

import datetime
import os
import re
import tempfile
import unicodedata
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

INDEX_NAME = "index.md"
INDEX_MARKER = "<!-- Generated by decision_records.py from the DR-###-slug.md files beside it; do not edit by hand. -->"
STATUSES = ("proposed", "rejected", "accepted", "deprecated")
DR_ID = re.compile(r"DR-[0-9]{3}")
FILE_NAME = re.compile(r"DR-([0-9]{3})-([a-z0-9]+(?:-[a-z0-9]+)*)\.md")
CHOSEN = re.compile(r'Chosen option: "(.+)", because (.+)\.', re.DOTALL)
FRONT_KEYS = {"status", "date", "decision-makers", "consulted", "informed", "superseded-by"}
EXPECTED = "DR-###-slug.md with MADR 4.0.0 YAML front matter"
CONTEXT, DRIVERS, OPTIONS, OUTCOME, PROS_CONS, MORE = (
    "Context and Problem Statement", "Decision Drivers", "Considered Options", "Decision Outcome",
    "Pros and Cons of the Options", "More Information")
SECTIONS = (CONTEXT, DRIVERS, OPTIONS, OUTCOME, PROS_CONS, MORE)
CONSEQUENCES, CONFIRMATION = "Consequences", "Confirmation"
HEADING = re.compile(r"(#{1,6}) +(\S.*?) *")
FENCE = re.compile(r" {0,3}(`{3,}|~{3,})")


class DecisionRecordError(ValueError):
    """A record, its name or the set of records breaks the MADR 4.0.0 layout."""


@dataclass(frozen=True)
class DecisionRecord:
    number: int
    slug: str
    title: str
    status: str
    date: datetime.date
    context: str
    options: tuple[str, ...]
    chosen: str
    justification: str
    decision_makers: tuple[str, ...] = ()
    consulted: tuple[str, ...] = ()
    informed: tuple[str, ...] = ()
    drivers: tuple[str, ...] = ()
    consequences: str | None = None
    confirmation: str | None = None
    pros_and_cons: str | None = None
    more_information: str | None = None
    superseded_by: tuple[str, ...] = ()

    @property
    def id(self) -> str:
        return f"DR-{self.number:03d}"

    @property
    def file_name(self) -> str:
        return f"{self.id}-{self.slug}.md"


# --- validation ------------------------------------------------------------------------------------------

def _check_text(what: str, value: object, *, single_line: bool = False) -> None:
    if not isinstance(value, str) or not value or value != value.strip():
        raise DecisionRecordError(f"{what} must be non-empty text without leading or trailing whitespace")
    if single_line and "\n" in value:
        raise DecisionRecordError(f"{what} must be one line")


def _check_list(what: str, values: object, *, required: bool) -> None:
    if not isinstance(values, tuple) or (required and not values):
        raise DecisionRecordError(f"{what} must be {'a non-empty' if required else 'a'} tuple of one-line texts")
    for value in values:
        _check_text(f"each of {what}", value, single_line=True)


def _check_identity(record: DecisionRecord) -> None:
    if not isinstance(record.number, int) or isinstance(record.number, bool) or not 1 <= record.number <= 999:
        raise DecisionRecordError("number must be an integer from 1 to 999")
    if not FILE_NAME.fullmatch(record.file_name):
        raise DecisionRecordError(f"slug {record.slug!r} must be lower-case words joined by hyphens")
    _check_text("title", record.title, single_line=True)
    if record.status not in STATUSES:
        raise DecisionRecordError(
            f"status {record.status!r} must be one of {', '.join(STATUSES)}; superseded is derived from "
            "superseded-by, never stored as a status")
    if type(record.date) is not datetime.date:
        raise DecisionRecordError("date must be a calendar date (YYYY-MM-DD)")


def _check_supersession(record: DecisionRecord) -> None:
    _check_list("superseded-by", record.superseded_by, required=False)
    for ident in record.superseded_by:
        if not DR_ID.fullmatch(ident):
            raise DecisionRecordError(f"superseded-by {ident!r} must be a DR-### id")
        if ident == record.id:
            raise DecisionRecordError(f"{record.id} cannot supersede itself")
    if len(set(record.superseded_by)) != len(record.superseded_by):
        raise DecisionRecordError("superseded-by names a record twice")


def _check(record: DecisionRecord) -> None:
    """The invariants of a record, for both reading and writing."""
    _check_identity(record)
    _check_supersession(record)
    _check_list("decision-makers", record.decision_makers, required=False)
    _check_list("consulted", record.consulted, required=False)
    _check_list("informed", record.informed, required=False)
    _check_list("drivers", record.drivers, required=False)
    _check_list("options", record.options, required=True)
    _check_text("context", record.context)
    _check_text("justification", record.justification, single_line=True)
    _check_text("chosen option", record.chosen, single_line=True)
    if record.chosen not in record.options:
        raise DecisionRecordError(f"chosen option {record.chosen!r} is not one of the considered options")
    for what, value in (("consequences", record.consequences), ("confirmation", record.confirmation),
                        ("pros_and_cons", record.pros_and_cons), ("more_information", record.more_information)):
        if value is not None:
            _check_text(what, value)


def slugify(title: str) -> str:
    """Lower-case ASCII words of `title` joined by hyphens. Raises DecisionRecordError for a title without any."""
    folded = unicodedata.normalize("NFKD", title).encode("ascii", "ignore").decode("ascii").lower()
    slug = "-".join(re.findall(r"[a-z0-9]+", folded))
    if not slug:
        raise DecisionRecordError(f"title {title!r} has no ASCII letter or digit to build a file name from")
    return slug


# --- parsing ---------------------------------------------------------------------------------------------

def _headings(lines: Sequence[str]) -> list[tuple[int, int, str]]:
    """(line index, level, text) of every ATX heading outside a fenced code block."""
    found: list[tuple[int, int, str]] = []
    fence: str | None = None
    for index, line in enumerate(lines):
        marker = FENCE.match(line) if not line.startswith("    ") else None
        if marker:
            if fence is None:
                fence = marker.group(1)[0]
            elif marker.group(1)[0] == fence:
                fence = None
            continue
        match = HEADING.fullmatch(line) if fence is None else None
        if match:
            found.append((index, len(match.group(1)), match.group(2)))
    return found


def _bullets(what: str, text: str) -> tuple[str, ...]:
    items = []
    for line in text.splitlines():
        if not line.startswith("* ") or not line[2:].strip():
            raise DecisionRecordError(f"{what} must be a list of '* item' lines, found {line!r}")
        items.append(line[2:].strip())
    return tuple(items)


def _sections(lines: list[str], cuts: list[tuple[int, int, str]]) -> dict[str, str]:
    sections: dict[str, str] = {}
    for position, (index, level, name) in enumerate(cuts):
        if level == 1:
            raise DecisionRecordError(f"a second '# {name}' title")
        if name not in SECTIONS:
            raise DecisionRecordError(f"unknown section '## {name}'; MADR 4.0.0 has {', '.join(SECTIONS)}")
        if name in sections:
            raise DecisionRecordError(f"section '## {name}' appears twice")
        end = cuts[position + 1][0] if position + 1 < len(cuts) else len(lines)
        content = "\n".join(lines[index + 1:end]).strip()
        if not content:
            raise DecisionRecordError(f"section '## {name}' is empty; leave it out instead")
        sections[name] = content
    return sections


def _outcome_parts(outcome: str) -> tuple[str, dict[str, str]]:
    """The outcome text before its first H3 part, and the `### Consequences` and `### Confirmation` parts."""
    lines = outcome.splitlines()
    parts = [(i, name) for i, level, name in _headings(lines) if level == 3]
    for name in (n for _, n in parts):
        if name not in (CONSEQUENCES, CONFIRMATION):
            raise DecisionRecordError(f"unknown part '### {name}' of the decision outcome")
    if len({n for _, n in parts}) != len(parts):
        raise DecisionRecordError("a part of the decision outcome appears twice")
    found: dict[str, str] = {}
    for position, (index, name) in enumerate(parts):
        end = parts[position + 1][0] if position + 1 < len(parts) else len(lines)
        content = "\n".join(lines[index + 1:end]).strip()
        if not content:
            raise DecisionRecordError(f"part '### {name}' is empty; leave it out instead")
        found[name] = content
    first = parts[0][0] if parts else len(lines)
    return "\n".join(lines[:first]).strip(), found


def _body(text: str) -> tuple[str, dict[str, str], dict[str, str]]:
    """The title, the text of each H2 section, and the H3 parts of the outcome."""
    lines = text.splitlines()
    heads = _headings(lines)
    if not heads or heads[0][0] != 0 or heads[0][1] != 1:
        raise DecisionRecordError("the body must start with a '# title' line")
    cuts = [(index, level, name) for index, level, name in heads[1:] if level <= 2]
    sections = _sections(lines, cuts)
    gap = lines[1:cuts[0][0] if cuts else len(lines)]
    if "".join(gap).strip():
        raise DecisionRecordError("text between the title and the first section")
    outcome_parts: dict[str, str] = {}
    if OUTCOME in sections:
        sections[OUTCOME], outcome_parts = _outcome_parts(sections[OUTCOME])
    return heads[0][2], sections, outcome_parts


def _front(text: str) -> tuple[dict[str, Any], str]:
    if not text.startswith("---\n"):
        raise DecisionRecordError(f"the file must start with '---' YAML front matter; expected {EXPECTED}")
    end = text.find("\n---\n", 3)
    if end < 0:
        raise DecisionRecordError("the YAML front matter is not closed by a '---' line")
    try:
        front = yaml.safe_load(text[4:end + 1])
    except yaml.YAMLError as error:
        raise DecisionRecordError(f"the YAML front matter is invalid: {error}") from error
    if not isinstance(front, dict):
        raise DecisionRecordError("the YAML front matter must be a mapping")
    unknown = sorted(set(front) - FRONT_KEYS)
    if unknown:
        raise DecisionRecordError(f"unknown front matter keys {unknown}; MADR 4.0.0 has {sorted(FRONT_KEYS)}")
    missing = [key for key in ("status", "date") if key not in front]
    if missing:
        raise DecisionRecordError(f"front matter lacks {', '.join(missing)}")
    return front, text[end + 5:].lstrip("\n")


def _names(front: dict[str, Any], key: str) -> tuple[str, ...]:
    value = front.get(key, [])
    if not isinstance(value, list):
        raise DecisionRecordError(f"{key} must be a YAML list of names")
    return tuple(value)


def parse_record(number: int, slug: str, text: str) -> DecisionRecord:
    """The record in `text`. Raises DecisionRecordError off the MADR 4.0.0 layout."""
    front, body = _front(text)
    title, sections, parts = _body(body)
    for name in (CONTEXT, OPTIONS, OUTCOME):
        if name not in sections:
            raise DecisionRecordError(f"section '## {name}' is missing")
    match = CHOSEN.fullmatch(sections[OUTCOME])
    if match is None:
        raise DecisionRecordError('the decision outcome must read: Chosen option: "<option>", because <why>.')
    record = DecisionRecord(
        number=number, slug=slug, title=title, status=front["status"], date=front["date"],
        decision_makers=_names(front, "decision-makers"), consulted=_names(front, "consulted"),
        informed=_names(front, "informed"), superseded_by=_names(front, "superseded-by"), context=sections[CONTEXT],
        drivers=_bullets(DRIVERS, sections[DRIVERS]) if DRIVERS in sections else (),
        options=_bullets(OPTIONS, sections[OPTIONS]), chosen=match.group(1), justification=match.group(2),
        consequences=parts.get(CONSEQUENCES), confirmation=parts.get(CONFIRMATION),
        pros_and_cons=sections.get(PROS_CONS), more_information=sections.get(MORE))
    _check(record)
    return record


def read_decision(path: Path) -> DecisionRecord:
    """The record in the file `path`, named DR-###-slug.md."""
    match = FILE_NAME.fullmatch(path.name)
    try:
        if match is None:
            raise DecisionRecordError(f"the name must be {EXPECTED} (lower-case slug words joined by hyphens)")
        try:
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError) as error:
            raise DecisionRecordError(f"cannot read it as UTF-8 text: {error}") from error
        return parse_record(int(match.group(1)), match.group(2), text)
    except DecisionRecordError as error:
        raise DecisionRecordError(f"{path}: {error}") from error


def read_decisions(directory: Path) -> list[DecisionRecord]:
    """Every record of `directory`, by number. `index.md` is the generated index and is not read."""
    if not directory.is_dir():
        raise DecisionRecordError(f"{directory} is not a directory")
    records = [read_decision(path) for path in sorted(directory.glob("DR-*.md"))]
    records.sort(key=lambda record: record.number)
    known = {record.id for record in records}
    for record in records:
        for ident in record.superseded_by:
            if ident not in known:
                raise DecisionRecordError(f"{directory / record.file_name}: superseded-by {ident} names no record")
    for first, second in zip(records, records[1:]):
        if first.number == second.number:
            raise DecisionRecordError(
                f"{directory}: {first.id} is used by {first.file_name} and {second.file_name}")
    return records


def find_decision(directory: Path, ident: str) -> DecisionRecord:
    """The record `DR-###` in `directory`, reading only its file. Raises DecisionRecordError for a bad id,
    no such record, or two files with one id."""
    if not DR_ID.fullmatch(ident):
        raise DecisionRecordError(f"{ident!r} is not a DR-### id")
    if not directory.is_dir():
        raise DecisionRecordError(f"{directory} is not a directory")
    found = sorted(directory.glob(f"{ident}-*.md"))
    if (old := directory / f"{ident}.md").exists():
        raise DecisionRecordError(f"{old} has an old-form name; expected {EXPECTED}")
    if not found:
        raise DecisionRecordError(f"{directory}: no record {ident}")
    if len(found) > 1:
        raise DecisionRecordError(f"{directory}: {ident} is used by {', '.join(p.name for p in found)}")
    return read_decision(found[0])


# --- writing ---------------------------------------------------------------------------------------------

def _section(heading: str, content: str, level: int = 2) -> str:
    return f"{'#' * level} {heading}\n\n{content}\n"


def render(record: DecisionRecord) -> str:
    """The file text of `record`."""
    front: dict[str, Any] = {"status": record.status, "date": record.date}
    if record.decision_makers:
        front["decision-makers"] = list(record.decision_makers)
    if record.consulted:
        front["consulted"] = list(record.consulted)
    if record.informed:
        front["informed"] = list(record.informed)
    if record.superseded_by:
        front["superseded-by"] = list(record.superseded_by)
    dumped = yaml.safe_dump(front, sort_keys=False, allow_unicode=True, width=10**6)
    blocks = [f"# {record.title}\n", _section(CONTEXT, record.context)]
    if record.drivers:
        blocks.append(_section(DRIVERS, "\n".join(f"* {item}" for item in record.drivers)))
    blocks.append(_section(OPTIONS, "\n".join(f"* {item}" for item in record.options)))
    outcome = f'Chosen option: "{record.chosen}", because {record.justification}.'
    if record.consequences:
        outcome += "\n\n" + _section(CONSEQUENCES, record.consequences, 3).rstrip("\n")
    if record.confirmation:
        outcome += "\n\n" + _section(CONFIRMATION, record.confirmation, 3).rstrip("\n")
    blocks.append(_section(OUTCOME, outcome))
    if record.pros_and_cons:
        blocks.append(_section(PROS_CONS, record.pros_and_cons))
    if record.more_information:
        blocks.append(_section(MORE, record.more_information))
    return f"---\n{dumped}---\n\n" + "\n".join(blocks)


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def render_index(records: Iterable[DecisionRecord]) -> str:
    rows = [f"| [{r.id}]({r.file_name}) | {_cell(r.title)} | {_cell(r.status)} | {r.date.isoformat()} |"
            for r in records]
    return "\n".join([INDEX_MARKER, "", "# Decision records", "", "| ID | Title | Status | Date |",
                      "|---|---|---|---|", *rows, ""])


def regenerate_index(directory: Path) -> Path:
    """Rewrite `directory`/index.md from its records. Raises DecisionRecordError on a bad record."""
    text = render_index(read_decisions(directory))
    handle, temp = tempfile.mkstemp(dir=directory, prefix=".index-", suffix=".tmp")
    try:
        with os.fdopen(handle, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(text)
        os.replace(temp, directory / INDEX_NAME)
    except BaseException:
        Path(temp).unlink(missing_ok=True)
        raise
    return directory / INDEX_NAME


def write_decision(directory: Path, *, title: str, status: str, date: datetime.date,
                   context: str, options: tuple[str, ...], chosen: str,
                   justification: str, decision_makers: tuple[str, ...] = (), consulted: tuple[str, ...] = (), informed: tuple[str, ...] = (),
                   drivers: tuple[str, ...] = (), consequences: str | None = None,
                   confirmation: str | None = None, pros_and_cons: str | None = None,
                   more_information: str | None = None, superseded_by: tuple[str, ...] = (),
                   number: int | None = None) -> Path:
    """Write `DR-###-slug.md` into `directory`, regenerate its index and return the record's path.

    The number is the next free one unless `number` names a free one. The function renders the input and
    parses it back before it writes a file, so text that cannot read back (a stray `## ` heading) raises
    DecisionRecordError. A malformed record already in `directory` raises too. Both leave the directory unchanged."""
    existing = read_decisions(directory) if directory.exists() else []
    taken = {record.number: record for record in existing}
    chosen_number = number if number is not None else max(taken, default=0) + 1
    if chosen_number in taken:
        raise DecisionRecordError(f"{directory}: DR-{chosen_number:03d} is already {taken[chosen_number].file_name}")
    record = DecisionRecord(
        number=chosen_number, slug=slugify(title), title=title, status=status, date=date,
        decision_makers=decision_makers, consulted=consulted, informed=informed, context=context,
        drivers=drivers, options=options, chosen=chosen, justification=justification,
        consequences=consequences, confirmation=confirmation, pros_and_cons=pros_and_cons,
        more_information=more_information, superseded_by=superseded_by)
    _check(record)
    for ident in superseded_by:
        if not any(r.id == ident for r in existing):
            raise DecisionRecordError(f"superseded-by {ident} names no record in {directory}")
    text = render(record)
    if parse_record(record.number, record.slug, text) != record:
        raise DecisionRecordError(
            f"{record.file_name}: the text does not read back as given; a heading line in a section "
            "(outside a code fence) is the usual cause")
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / record.file_name
    with path.open("x", encoding="utf-8", newline="\n") as stream:
        stream.write(text)
    regenerate_index(directory)
    return path

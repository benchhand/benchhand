#!/usr/bin/env python3
"""Characterization tests for installer ownership paths, run through the CLI."""

from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

CAD = Path(__file__).resolve().parents[1]
INSTALLER = CAD / "harness/install.py"
STATE_NAME = ".cad-agent-install.json"
AGENT_KEY = ".claude/agents/cad-analyst.md"
MARKER = "<!-- Generated by cad-agent; do not edit. -->"


class InstallerOwnershipPathTests(unittest.TestCase):
    def setUp(self) -> None:
        temporary = tempfile.TemporaryDirectory(prefix="cad-install-paths-")
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name).resolve()
        self.project = self.root / "project"
        self.project.mkdir()
        self.home = self.root / "home"
        self.home.mkdir()
        self.state = self.project / STATE_NAME

    def run_installer(self, *args: str) -> subprocess.CompletedProcess[str]:
        env = {**os.environ, "HOME": str(self.home)}
        return subprocess.run(
            [sys.executable, str(INSTALLER), *args, "--project", str(self.project)],
            cwd=self.project,
            env=env,
            capture_output=True,
            text=True,
            timeout=60,
        )

    def run_ok(self, *args: str) -> str:
        result = self.run_installer(*args)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        return result.stdout

    def owned_files(self) -> dict[str, str]:
        return json.loads(self.state.read_text(encoding="utf-8"))["files"]

    def test_owned_unmodified_file_that_differs_from_source_is_updated(self) -> None:
        self.run_ok("--harness", "claude")
        target = self.project / AGENT_KEY
        source_bytes = target.read_bytes()
        target.write_bytes(b"older generated version\n")
        state = json.loads(self.state.read_text(encoding="utf-8"))
        state["files"][AGENT_KEY] = hashlib.sha256(
            b"older generated version\n"
        ).hexdigest()
        self.state.write_text(json.dumps(state), encoding="utf-8")

        output = self.run_ok("--harness", "claude")

        self.assertEqual(target.read_bytes(), source_bytes)
        self.assertEqual(output.splitlines(), [f"installed {target}"])
        self.assertEqual(
            self.owned_files()[AGENT_KEY], hashlib.sha256(source_bytes).hexdigest()
        )

    def test_unowned_file_identical_to_source_is_claimed_without_rewrite(self) -> None:
        self.run_ok("--harness", "claude")
        self.state.unlink()

        dry = self.run_ok("--harness", "claude", "--dry-run")
        self.assertIn(f"would keep {self.project / AGENT_KEY}", dry)
        self.assertIn(f"would record ownership {self.state}", dry)
        self.assertFalse(self.state.exists())

        output = self.run_ok("--harness", "claude")
        self.assertEqual(output.splitlines(), [f"recorded {self.state}"])
        self.assertIn(AGENT_KEY, self.owned_files())

    def test_unowned_generated_file_that_differs_from_source_is_refused(self) -> None:
        target = self.project / AGENT_KEY
        target.parent.mkdir(parents=True)
        target.write_text(f"{MARKER}\nstale generated content\n", encoding="utf-8")

        result = self.run_installer("--harness", "claude")

        self.assertEqual(result.returncode, 1)
        self.assertEqual(
            result.stderr.strip(),
            f"FAIL: generated CAD file differs from the current source; refusing to overwrite {target}",
        )
        self.assertEqual(
            target.read_text(encoding="utf-8"), f"{MARKER}\nstale generated content\n"
        )
        self.assertFalse(self.state.exists())

    def test_uninstall_of_one_harness_keeps_ownership_of_the_others(self) -> None:
        self.run_ok("--harness", "claude")
        self.run_ok("--harness", "codex")
        claude_agent = self.project / AGENT_KEY
        codex_files = [
            key for key in self.owned_files() if key.startswith((".agents/", ".codex/"))
        ]
        self.assertTrue(codex_files)

        dry = self.run_ok("--harness", "claude", "--uninstall", "--dry-run")
        self.assertIn(f"would uninstall {claude_agent}", dry)
        self.assertIn(f"would update ownership {self.state}", dry)
        self.assertTrue(claude_agent.exists())

        output = self.run_ok("--harness", "claude", "--uninstall")

        self.assertIn(f"uninstalled {claude_agent}", output)
        self.assertNotIn("removed", output)
        self.assertFalse((self.project / ".claude").exists())
        self.assertEqual(sorted(self.owned_files()), sorted(codex_files))
        self.assertTrue(all((self.project / key).is_file() for key in codex_files))


if __name__ == "__main__":
    unittest.main()
